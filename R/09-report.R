# ============================================================================
# cade: 报告生成 与 双参考选择建议
#
# ★ 本文件对真实性的保证 ★
#   report() 与 recommend_reference() 都是**只读**的。
#   它们不调用 compose_prediction()，不重算任何 pred/resid，也不改任何对象。
#   所有数字都从传入的对象里**原样转印**。
#   这一点由 test-report.R 里的一条测试强制：报告里出现的每个数字，
#   必须能在传入对象中找到完全相同的值。
# ============================================================================

#' Render a publication-ready report from a decomposition
#'
#' @param decomp Output of [decompose_composition()].
#' @param file Path to write the report to. If `NULL`, the report is returned as
#'   a character vector and printed.
#' @param title Report title.
#' @param calibrate Include the calibration section (calls [check_calibration()]).
#' @param attribute Include the attribution section (calls [attribute_genes()]).
#' @param truth Optional output of [simulate_pseudobulk()]`$truth`. When given, a
#'   known-answer scoring section is added.
#' @param top_n Number of genes to list by absolute residual.
#'
#' @return Invisibly, the character vector of the report. When `file` is given
#'   the report is also written there.
#'
#' @details
#' **The report does not compute anything.** It calls the same functions a user
#' would call interactively and transcribes their output. In particular it never
#' re-derives `pred` or `resid`; it reads them off `decomp`. A test enforces
#' this ("report numbers are transcription, not recomputation").
#'
#' The whole point of the upstream checks is that a number without its
#' calibration is not interpretable. So the calibration section is included by
#' default and its verdict is printed at the top, not in an appendix.
#'
#' @examples
#' \donttest{
#' set.seed(1)
#' d <- data.frame(gene = paste0("g", 1:50), obs = rnorm(50),
#'                 pred = rnorm(50) * 0.5, resid = rnorm(50) * 0.5,
#'                 pct = rnorm(50), mean_expr = runif(50, 1, 100))
#' class(d) <- c("cade_decomp", "data.frame")
#' cat(report(d), sep = "\n")
#' }
#' @export
report <- function(decomp, file = NULL, title = "cade report",
                   calibrate = TRUE, attribute = TRUE, truth = NULL,
                   top_n = 15) {

  need <- c("gene", "obs", "pred", "resid")
  miss <- setdiff(need, names(decomp))
  if (length(miss))
    stop(sprintf("`decomp` is missing column(s): %s", paste(miss, collapse = ", ")))

  L <- character(0)
  sec <- 1L
  add <- function(...) L <<- c(L, sprintf(...))
  add("# %s", title)
  add("")
  add("Generated by **cade** %s on %s.",
      tryCatch(as.character(utils::packageVersion("cade")),
               error = function(e) "0.9.0"),
      format(Sys.time(), "%Y-%m-%d %H:%M"))
  add("")

  ## ---------- 1. 输入概览（全部转印）----------
  add("## 1. Input summary")
  add("")
  add("| quantity | value |")
  add("|---|---|")
  add("| genes | %d |", nrow(decomp))
  add("| genes with a defined composition term | %d |",
      sum(is.finite(decomp$pred)))
  rng <- function(v) sprintf("%+.2f to %+.2f", min(v, na.rm = TRUE), max(v, na.rm = TRUE))
  add("| observed log2 fold change | %s |", rng(decomp$obs))
  add("| composition term | %s |", rng(decomp$pred))
  add("| within-cell residual | %s |", rng(decomp$resid))
  add("")

  ## ---------- 2. calibration ----------
  n_dropped <- 0
  if (calibrate && "mean_expr" %in% names(decomp)) {
    sec <- sec + 1; add("## %d. Calibration", sec)
    add("")
    cal <- tryCatch(check_calibration(decomp), error = function(e) NULL)
    if (is.null(cal)) {
      add("_Calibration could not be computed (too few usable genes)._")
      add("")
    } else {
      add("**Verdict.** %s", calibration_verdict(cal))
      add("")
      add("| stratum | n | slope | intercept | R2 | Pearson |")
      add("|---|---|---|---|---|---|")
      for (i in seq_len(nrow(cal)))
        add("| %s | %d | %+.3f | %+.3f | %.3f | %.3f |", cal$label[i], cal$n[i],
            cal$slope[i], cal$intercept[i], cal$r2[i], cal$pearson[i])
      add("")
      last <- cal[nrow(cal), ]
      if (last$slope < 0.7 || last$r2 < 0.05) {
        add("%s", paste("> **Do not interpret the residual column of this report as a", "within-cell effect.** The calibration above does not support it."))
        add("")
      }
    }
  } else n_dropped <- n_dropped + 1

  ## ---------- 3. top genes ----------
  sec <- sec + 1; add("## %d. Genes with the largest within-cell residual", sec)
  add("")
  add("%s", "Sorted by |residual|. `pct` is `resid / obs` and is **signed**; a residual")
  add("%s", "of opposite sign to `obs` means the composition term overshot.")
  add("")
  ord <- order(-abs(decomp$resid))
  k <- min(top_n, nrow(decomp))
  sel <- decomp[ord[seq_len(k)], , drop = FALSE]
  has_pct <- "pct" %in% names(sel)
  add("| gene | observed | composition | residual |%s", if (has_pct) " pct |" else "")
  add("|---|---|---|---|%s", if (has_pct) "---|" else "")
  for (i in seq_len(nrow(sel)))
    add("| %s | %+.2f | %+.2f | %+.2f |%s", sel$gene[i], sel$obs[i], sel$pred[i],
        sel$resid[i], if (has_pct) sprintf(" %+.2f |", sel$pct[i]) else "")
  add("")

  ## ---------- 4. 归类（转印）----------
  if (attribute &&
      all(c("resid", "pct") %in% names(decomp))) {
    sec <- sec + 1; add("## %d. Attribution", sec)
    add("")
    ok <- !is.na(decomp$pct) & abs(decomp$obs) >= 0
    at <- tryCatch(attribute_genes(decomp[ok, , drop = FALSE], min_obs = 0.3),
                   error = function(e) NULL)
    if (is.null(at)) {
      add("_Attribution could not be computed._")
      add("")
    } else {
      tb <- table(at$class)
      add("%s", "Thresholds 0.3 / 0.7 on the signed `pct`; genes with |observed| < 0.3")
      add("%s", "are labelled `unchanged`, and genes whose residual has the opposite")
      add("%s", "sign to `obs` are labelled `over-predicted`.")
      add("")
      add("| class | genes |")
      add("|---|---|")
      for (i in seq_along(tb)) add("| %s | %d |", names(tb)[i], tb[i])
      add("")

      ## 稳定性（转印）
      sens <- tryCatch(attribute_sensitivity(decomp[ok, , drop = FALSE]),
                       error = function(e) NULL)
      if (!is.null(sens)) {
        unstable <- sens[!sens$stable, , drop = FALSE]
        add("Label stability across 6 thresholds (0.20 to 0.45):")
        add("")
        add("| genes | count |")
        add("|---|---|")
        add("| same label at every threshold | %d |", sum(sens$stable))
        add("| label depends on threshold | %d |", nrow(unstable))
        add("")
        if (nrow(unstable)) {
          add("Threshold-dependent genes: %s",
              paste(utils::head(unstable$gene, 20), collapse = ", "))
          add("")
        }
      }
    }
  }

  ## ---------- 5. 已知答案打分（转印）----------
  if (!is.null(truth)) {
    sec <- sec + 1; add("## %d. Known-answer check", sec)
    add("")
    ig <- attr(truth, "intrinsic_genes")
    sc <- tryCatch(score_simulation(decomp, truth, ig), error = function(e) NULL)
    if (is.null(sc)) {
      add("_Scoring failed: check that `truth` has columns `gene`, `composition`, `intrinsic`._")
    } else {
      add("| metric | value |")
      add("|---|---|")
      add("| genes scored | %d |", sc$n_gene)
      add("| correlation of composition term with truth | %.4f |", sc$cor_pred)
      add("| median absolute error of composition term | %.4f |", sc$median_error_pred)
      add("| recovery of the injected within-cell change | %.3f |", sc$recovery_intrinsic)
      add("| false-positive rate among unchanged genes | %.4f |", sc$false_positive_rate)
    }
    add("")
  }

  ## ---------- 6. 方法说明 ----------
  sec <- sec + 1; add("## %d. What this report does and does not say", sec)
  add("")
  add("%s", "- `composition` is `log2(sum_k f_case[k] mu[k,g] / sum_k f_ctrl[k] mu[k,g])`,")
  add("%s", "  computed from the per-cell means of the reference you supplied.")
  add("%s", "- `residual = observed - composition` is a **bookkeeping identity**, not a")
  add("%s", "  causal claim. It equals the within-cell effect only if the reference")
  add("%s", "  matches the tissue and if deconvolution is unbiased.")
  add("%s", "- The calibration section is the gate: if it fails, the residual column")
  add("%s", "  should not be interpreted.")
  add("")

  if (n_dropped)
    add("_Note: the calibration section was skipped._")

  if (!is.null(file)) {
    writeLines(L, file, useBytes = TRUE)
    message("report written to ", file)
  } else {
    cat(L, sep = "\n")
  }
  invisible(L)
}


#' Advisory guidance for choosing between two references
#'
#' @param cmp Output of [compare_references()].
#' @param a_has_normal,b_has_normal Logical or `NA`. Does reference A / B contain
#'   any non-diseased tissue? `NA` means unknown.
#' @param a_cells_per_type,b_cells_per_type Named integer vectors: the number of
#'   cells of each type in each reference. Optional.
#' @param a_label,b_label Display names.
#'
#' @return A list with `verdict` (character), `evidence` (data frame) and
#'   `actions` (character vector).
#'
#' @details
#' This function **does not pick a winner from the data**. A reference that
#' produces a smoother calibration is not thereby the correct one, and choosing
#' on that basis is how the selection becomes circular. What it does instead:
#'
#' 1. reports whether the two references disagree (from `cmp$agreement`);
#' 2. evaluates the two properties that can be checked *without* looking at the
#'    output: whether the reference contains normal tissue, and whether any cell
#'    type is starved;
#' 3. states plainly what may and may not be concluded.
#'
#' If both references pass the provenance checks and still disagree, the
#' disagreement is the finding: report both, do not choose.
#'
#' @examples
#' mu <- matrix(c(500, 50, 300, 40), nrow = 2,
#'              dimnames = list(c("A", "B"), c("g1", "g2")))
#' fr <- matrix(c(0.8, 0.2, 0.8, 0.2, 0.2, 0.8, 0.2, 0.8), nrow = 4,
#'              byrow = TRUE, dimnames = list(paste0("s", 1:4), c("A", "B")))
#' ob <- c(g1 = 0.5, g2 = -0.2)
#' ic <- c(FALSE, FALSE, TRUE, TRUE)
#' cmp <- compare_references(ob, fr, fr, mu, mu, ic, validate = FALSE)
#' recommend_reference(cmp, a_has_normal = TRUE, b_has_normal = FALSE)$verdict
#' @export
recommend_reference <- function(cmp, a_has_normal = NA, b_has_normal = NA,
                                a_cells_per_type = NULL, b_cells_per_type = NULL,
                                a_label = "reference A", b_label = "reference B") {
  if (is.null(cmp$agreement))
    stop("`cmp` must be the output of compare_references().")
  ag <- cmp$agreement

  ev <- data.frame(
    check = c(paste0(a_label, " contains normal tissue"),
              paste0(b_label, " contains normal tissue"),
              paste0(a_label, " smallest cell type"),
              paste0(b_label, " smallest cell type"),
              "residual correlation between references",
              "sign agreement of residuals"),
    value = c(
      if (is.na(a_has_normal)) "unknown" else as.character(a_has_normal),
      if (is.na(b_has_normal)) "unknown" else as.character(b_has_normal),
      if (is.null(a_cells_per_type)) "unknown" else as.character(min(a_cells_per_type)),
      if (is.null(b_cells_per_type)) "unknown" else as.character(min(b_cells_per_type)),
      sprintf("%.3f", ag$cor_resid),
      sprintf("%.1f%%", 100 * ag$sign_agree)),
    stringsAsFactors = FALSE)

  ## ---- 只依据"可独立核实的事实"给建议 ----
  starved <- function(v) !is.null(v) && min(v) < 100
  trustworthy <- function(has_n, cells) {
    if (is.na(has_n)) return(NA)
    has_n && !starved(cells)
  }
  ta <- trustworthy(a_has_normal, a_cells_per_type)
  tb <- trustworthy(b_has_normal, b_cells_per_type)

  disagree <- ag$sign_agree < 0.95

  verdict <- if (identical(ta, FALSE) && identical(tb, FALSE)) {
    "Neither reference passes the provenance checks. Do not report the residual as a within-cell effect."
  } else if (identical(ta, FALSE)) {
    sprintf("%s fails the provenance checks (%s). Prefer %s, and report %s's result as a sensitivity analysis only.",
            a_label,
            if (is.na(a_has_normal)) "provenance unknown" else "no normal tissue and/or a starved cell type",
            b_label, a_label)
  } else if (identical(tb, FALSE)) {
    sprintf("%s fails the provenance checks (%s). Prefer %s, and report %s's result as a sensitivity analysis only.",
            b_label,
            if (is.na(b_has_normal)) "provenance unknown" else "no normal tissue and/or a starved cell type",
            a_label, b_label)
  } else if (is.na(ta) || is.na(tb)) {
    paste0("Provenance is unknown for at least one reference, so no recommendation can be made ",
           "on provenance grounds. Report both and state that the choice was not resolved.")
  } else if (disagree) {
    paste0("Both references pass the provenance checks but they disagree (sign agreement ",
           sprintf("%.1f%%", 100 * ag$sign_agree), "). ",
           "**The disagreement is the finding.** Report both sets of numbers; do not select.")
  } else {
    paste0("Both references pass the provenance checks and agree (sign agreement ",
           sprintf("%.1f%%", 100 * ag$sign_agree), "). Either may be reported; state which one you used.")
  }

  actions <- character(0)
  if (is.na(a_has_normal) || is.na(b_has_normal))
    actions <- c(actions, "Establish whether each reference contains non-diseased tissue. This cannot be inferred from the data.")
  if (is.null(a_cells_per_type) || is.null(b_cells_per_type))
    actions <- c(actions, "Count the cells per type in each reference; a type with <100 cells has an unstable mean and an unstable fraction.")
  if (disagree)
    actions <- c(actions, "List the genes whose residual sign flips (cmp$discordant) and report them explicitly.")
  if (starved(a_cells_per_type) || starved(b_cells_per_type))
    actions <- c(actions, "Consider merging the starved cell type with its nearest neighbour, or dropping it from both frac and mu.")
  actions <- c(actions,
               "Do not choose a reference because its calibration slope is closer to 1. That criterion is circular.")

  cat("\n========== reference recommendation ==========\n\n")
  for (i in seq_len(nrow(ev))) cat(sprintf("  %-46s %s\n", ev$check[i], ev$value[i]))
  cat("\n  VERDICT\n")
  cat(sprintf("    %s\n\n", verdict))
  if (length(actions)) {
    cat("  ACTIONS\n")
    for (a in actions) cat(sprintf("    - %s\n", a))
    cat("\n")
  }
  cat("==============================================\n\n")

  list(verdict = verdict, evidence = ev, actions = actions)
}
